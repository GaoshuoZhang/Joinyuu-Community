import type { CommunityEvent, EventEnrollment } from '@prisma/client'

/* DB 行 → CommunityEvent 形状（内嵌 enrollments 去除 id/eventId；可空字段 null → undefined）。
 * events 域与工作台聚合（dashboard.upcomingEvents）共用，保证两处形状不漂移。 */
export function toEventDto(event: CommunityEvent, enrollments: EventEnrollment[]): Record<string, unknown> {
  return {
    id: event.id,
    createdAt: event.createdAt,
    title: event.title,
    coverUrl: event.coverUrl ?? undefined,
    type: event.type,
    startTime: event.startTime,
    endTime: event.endTime,
    location: event.location,
    capacity: event.capacity,
    speaker: event.speaker,
    host: event.host,
    status: event.status,
    enrollmentOpen: event.enrollmentOpen,
    visibilityIdentities: event.visibilityIdentities,
    visibilityLevels: event.visibilityLevels,
    enrollmentIdentities: event.enrollmentIdentities,
    enrollmentLevels: event.enrollmentLevels,
    requireReview: event.requireReview,
    enrollmentDeadline: event.enrollmentDeadline ?? undefined,
    scheduledAt: event.scheduledAt ?? undefined,
    enrollPoints: event.enrollPoints ?? undefined,
    checkinPoints: event.checkinPoints ?? undefined,
    venueLat: event.venueLat ?? undefined,
    venueLng: event.venueLng ?? undefined,
    checkinRadiusM: event.checkinRadiusM ?? undefined,
    checkinOpenMin: event.checkinOpenMin ?? undefined,
    checkinCloseMin: event.checkinCloseMin ?? undefined,
    checkinLocationRequired: event.checkinLocationRequired,
    checkinCodeRequired: event.checkinCodeRequired,
    checkinCode: event.checkinCode ?? undefined,
    cancelDeadlineHours: event.cancelDeadlineHours ?? undefined,
    rescheduledTo: event.rescheduledTo ?? undefined,
    description: event.description,
    tags: event.tags,
    deletedAt: event.deletedAt ?? undefined,
    enrollments: enrollments.map((en) => ({
      userId: en.userId,
      name: en.name,
      enterprise: en.enterprise,
      phone: en.phone,
      appliedAt: en.appliedAt,
      status: en.status,
      checkedIn: en.checkedIn,
      checkInAt: en.checkInAt,
      waitlistOrder: en.waitlistOrder ?? undefined,
      checkinLat: en.checkinLat ?? undefined,
      checkinLng: en.checkinLng ?? undefined,
      checkinMethod: en.checkinMethod ?? undefined,
    })),
  }
}
